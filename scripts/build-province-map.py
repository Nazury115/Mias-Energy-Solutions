"""Generate src/content/zambia-map.ts from geoBoundaries' Zambia ADM1 (province) GeoJSON.

Usage (the source file stays outside the repository):
    python -I scripts/build-province-map.py <geoBoundaries-ZMB-ADM1_simplified.geojson> src/content/zambia-map.ts

Source: geoBoundaries gbOpen ZMB ADM1 (Zambia Data Hub, 2020), CC BY 4.0. Standard library only.
"""
import json
import math
import sys
from pathlib import Path

WIDTH = 1000
TOLERANCE = 0.9  # Douglas-Peucker tolerance in output pixels; raise to shrink the file
LUSAKA_CITY = (28.2833, -15.4167)  # lon, lat


def simplify(points, tolerance):
    """Iterative Douglas-Peucker on a list of (x, y) points."""
    if len(points) < 3:
        return points
    keep = [False] * len(points)
    keep[0] = keep[-1] = True
    stack = [(0, len(points) - 1)]
    while stack:
        start, end = stack.pop()
        (x1, y1), (x2, y2) = points[start], points[end]
        dx, dy = x2 - x1, y2 - y1
        length = math.hypot(dx, dy) or 1e-12
        worst, index = 0.0, None
        for i in range(start + 1, end):
            px, py = points[i]
            distance = abs(dy * px - dx * py + x2 * y1 - y2 * x1) / length
            if distance > worst:
                worst, index = distance, i
        if index is not None and worst > tolerance:
            keep[index] = True
            stack += [(start, index), (index, end)]
    return [point for point, kept in zip(points, keep) if kept]


def simplify_ring(ring, tolerance):
    """Closed rings start and end on the same point, so split at the farthest point and simplify each half."""
    far = max(range(len(ring)), key=lambda i: math.dist(ring[0], ring[i]))
    return simplify(ring[:far + 1], tolerance)[:-1] + simplify(ring[far:], tolerance)


def centroid(ring):
    """Area-weighted centroid of a closed ring."""
    area = cx = cy = 0.0
    for (x1, y1), (x2, y2) in zip(ring, ring[1:] + ring[:1]):
        cross = x1 * y2 - x2 * y1
        area += cross
        cx += (x1 + x2) * cross
        cy += (y1 + y2) * cross
    area *= 0.5
    return (cx / (6 * area), cy / (6 * area)) if area else ring[0]


def main(source, target):
    data = json.loads(Path(source).read_text(encoding="utf-8"))
    rings = {}
    for feature in data["features"]:
        geometry = feature["geometry"]
        polygons = [geometry["coordinates"]] if geometry["type"] == "Polygon" else geometry["coordinates"]
        rings[feature["properties"]["shapeName"]] = (feature["properties"]["shapeISO"], [polygon[0] for polygon in polygons])

    lons = [lon for _, polygons in rings.values() for ring in polygons for lon, _ in ring]
    lats = [lat for _, polygons in rings.values() for ring in polygons for _, lat in ring]
    squash = math.cos(math.radians((min(lats) + max(lats)) / 2))  # equirectangular, true at mid-latitude
    scale = WIDTH / ((max(lons) - min(lons)) * squash)
    height = round((max(lats) - min(lats)) * scale)

    def project(lon, lat):
        return ((lon - min(lons)) * squash * scale, (max(lats) - lat) * scale)

    provinces = []
    for name in sorted(rings):
        iso, polygons = rings[name]
        parts, largest = [], []
        for ring in polygons:
            points = simplify_ring([project(lon, lat) for lon, lat in ring], TOLERANCE)
            if len(points) < 4:
                continue
            largest = max(largest, points, key=len)
            parts.append("M" + "L".join(f"{x:.1f},{y:.1f}" for x, y in points[:-1]) + "Z")
        label = centroid(largest[:-1])
        provinces.append({"name": name, "iso": iso, "path": "".join(parts), "label": [round(label[0], 1), round(label[1], 1)]})

    city = project(*LUSAKA_CITY)
    module = (
        "// Generated by scripts/build-province-map.py. Do not edit by hand.\n"
        "// Boundaries: geoBoundaries gbOpen ZMB ADM1 (source: Zambia Data Hub, 2020), CC BY 4.0.\n"
        f"export const zambiaMap = {json.dumps({'viewBox': f'0 0 {WIDTH} {height}', 'lusakaCity': [round(city[0], 1), round(city[1], 1)], 'provinces': provinces}, indent=1)} as const;\n"
    )
    Path(target).write_text(module, encoding="utf-8")
    print(f"{len(provinces)} provinces, viewBox 0 0 {WIDTH} {height}, {len(module.encode()) / 1024:.1f} KB")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
